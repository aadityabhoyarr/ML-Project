"""Streamlit Web Application: AI vs Human Text Detector.

Interactive demo powered by the best-performing model trained under
Condition B (truncated to 50 words to eliminate dataset length bias).
"""

import os
import sys
import joblib
import pandas as pd
import streamlit as st

# Configure page layout and title
st.set_page_config(
    page_title="AI vs Human Text Detector",
    page_icon="🔍",
    layout="wide",
)

# Ensure local imports work
root_dir = os.path.dirname(os.path.abspath(__file__))
if root_dir not in sys.path:
    sys.path.insert(0, root_dir)

from src import features, preprocess
sys.modules["features"] = features
sys.modules["preprocess"] = preprocess

from src.features import (
    HandcraftedFeatureExtractor,
    extract_handcrafted_dict,
    HANDCRAFTED_FEATURE_LABELS,
)
from src.preprocess import clean_text_for_tfidf, truncate_text

# Benchmark averages from training set (Condition B: first 50 words)
BENCHMARK_MEANS = {
    "Avg Sentence Length (words/sent)": {"Human (0)": "19.05", "AI (1)": "15.28"},
    "Std Sentence Length (sent variation)": {"Human (0)": "6.09", "AI (1)": "4.75"},
    "Vocabulary Richness (Type-Token Ratio)": {"Human (0)": "0.84", "AI (1)": "0.87"},
    "Avg Word Length (chars/word)": {"Human (0)": "6.16", "AI (1)": "6.05"},
    "Punctuation Ratio (punct/chars)": {"Human (0)": "0.024", "AI (1)": "0.024"},
    "Comma Ratio (commas/words)": {"Human (0)": "0.054", "AI (1)": "0.032"},
    "Uppercase Ratio (upper/chars)": {"Human (0)": "0.028", "AI (1)": "0.023"},
    "Digit Ratio (digits/chars)": {"Human (0)": "0.005", "AI (1)": "0.004"},
}

# Pre-packaged test samples for convenience
SAMPLE_HUMAN = (
    "In this investigation, we analyze the structural and optical properties of pulsed-laser deposited "
    "thin films under high thermal stress. X-ray diffraction patterns revealed a transition from amorphous "
    "to polycrystalline phases at temperatures exceeding 450 degrees Celsius, exhibiting an average grain "
    "size of 24 nanometers. These empirical observations suggest enhanced charge-carrier mobility suitable for "
    "photovoltaic applications, although further carrier-lifetime measurements remain necessary."
)

SAMPLE_AI = (
    "This study explores the chemical composition of thermal springs, assessing their therapeutic "
    "potential and geothermal relevance in regional environmental science. The results provide critical "
    "insights into sustainable water management and geothermal energy applications."
)


@st.cache_resource
def load_detector_model():
    """Loads the best model trained on Condition B (Fair Truncated Text)."""
    model_path = os.path.join(root_dir, "models", "best_model_condition_b.joblib")
    if not os.path.exists(model_path):
        # Fallback if run from a different relative location
        model_path = os.path.join("models", "best_model_condition_b.joblib")

    if not os.path.exists(model_path):
        st.error(f"Model file not found at '{model_path}'. Please run 'python src/train.py' first.")
        return None, None

    checkpoint = joblib.load(model_path)
    if isinstance(checkpoint, dict) and "pipeline" in checkpoint:
        return checkpoint["pipeline"], checkpoint
    return checkpoint, {"model_name": "Condition B Best Model", "feature_set": "TF-IDF"}


def main():
    st.title("🔍 AI vs Human Text Detector")
    st.markdown(
        "**Machine Learning Course Project** — Evaluates whether a text sample was authored by a "
        "**Human** or generated by an **AI (LLM)** using stylometric and n-gram lexical analysis."
    )

    # Sidebar: Model and Course Metadata
    with st.sidebar:
        st.header("⚙️ Model Configuration")
        pipeline, meta = load_detector_model()

        if meta:
            st.success(f"**Loaded Model:** {meta.get('model_name', 'Best Model')}")
            st.info(f"**Feature Set:** {meta.get('feature_set', 'TF-IDF')}")
            st.info(f"**Evaluation Mode:** Condition B (Truncated 50 words)")
            if "test_accuracy" in meta:
                st.metric("Test Accuracy", f"{meta['test_accuracy']*100:.2f}%")
            if "test_f1" in meta:
                st.metric("Test F1-Score", f"{meta['test_f1']:.4f}")

        st.markdown("---")
        st.subheader("💡 Why Condition B?")
        st.markdown(
            "In raw datasets, human texts are often significantly longer than AI snippets. "
            "To prevent the classifier from taking a shortcut (*'short = AI, long = human'*), "
            "this model is strictly trained and evaluated on the **first 50 words** of each text."
        )

        st.markdown("---")
        st.caption("Developed with Python & Scikit-Learn.")

    if pipeline is None:
        st.stop()

    # User Input Controls
    st.subheader("📝 Enter Text to Analyze")

    # Sample selector buttons
    col_s1, col_s2, col_s3 = st.columns([1, 1, 3])
    if "input_text" not in st.session_state:
        st.session_state["input_text"] = ""

    with col_s1:
        if st.button("📄 Load Human Sample"):
            st.session_state["input_text"] = SAMPLE_HUMAN

    with col_s2:
        if st.button("🤖 Load AI Sample"):
            st.session_state["input_text"] = SAMPLE_AI

    with col_s3:
        if st.button("🔄 Clear Input"):
            st.session_state["input_text"] = ""

    user_text = st.text_area(
        "Paste an article, essay, or abstract below:",
        value=st.session_state["input_text"],
        height=180,
        placeholder="Enter at least 20 words for the most reliable stylometric classification...",
    )

    # Word count feedback
    words = user_text.strip().split()
    word_count = len(words)
    st.caption(f"Word count: **{word_count} words** (Model evaluates the first 50 words)")

    # Warning for very short text
    if 0 < word_count < 20:
        st.warning(
            "⚠️ **Warning:** Input contains fewer than 20 words. Stylometric distributions "
            "(sentence length variance, vocabulary richness, punctuation ratios) require sufficient "
            "context. Results on very short text may be unreliable."
        )

    # Analyze Button
    if st.button("🚀 Analyze Text", type="primary"):
        if not user_text.strip():
            st.error("Please enter some text before analyzing.")
            return

        # Condition B Truncation (identically to training pipeline)
        truncated_input = truncate_text(user_text, max_words=50)

        # Route input format based on pipeline steps
        if "tfidf" in pipeline.named_steps:
            cleaned_input = clean_text_for_tfidf(truncated_input)
            model_input = [cleaned_input]
        else:
            model_input = [truncated_input]

        # Model Inference
        probs = pipeline.predict_proba(model_input)[0]
        prob_human = float(probs[0])
        prob_ai = float(probs[1])

        # Prediction Display
        st.markdown("---")
        st.subheader("🎯 Classification Result")

        res_col1, res_col2 = st.columns([1, 1])

        with res_col1:
            if prob_ai >= 0.5:
                conf = prob_ai * 100
                st.error(f"### 🤖 **{conf:.1f}% likely AI-generated**")
                st.progress(prob_ai)
                st.caption(f"Estimated class probabilities: AI = {prob_ai*100:.1f}%, Human = {prob_human*100:.1f}%")
            else:
                conf = prob_human * 100
                st.success(f"### 👤 **{conf:.1f}% likely Human-written**")
                st.progress(prob_human)
                st.caption(f"Estimated class probabilities: Human = {prob_human*100:.1f}%, AI = {prob_ai*100:.1f}%")

        with res_col2:
            st.markdown(
                "**How the Decision Was Formed:**\n"
                f"- Input text was truncated to **{len(truncated_input.split())} words**.\n"
                f"- Evaluated using **{meta.get('model_name', 'Trained')}** classifier on **{meta.get('feature_set', 'TF-IDF')}** features.\n"
                "- Lexical n-grams and vocabulary signatures were matched against academic benchmarks."
            )

        # Handcrafted Stylometric Feature Breakdown Table
        st.markdown("---")
        st.subheader("📊 Stylometric Feature Breakdown (First 50 Words)")
        st.markdown(
            "The table below shows the 8 length-independent linguistic features extracted from your input, "
            "compared with benchmark dataset averages for Human and AI texts:"
        )

        user_feats = extract_handcrafted_dict(truncated_input)
        feature_rows = []
        for feat_name, user_val in user_feats.items():
            bench = BENCHMARK_MEANS.get(feat_name, {"Human (0)": "N/A", "AI (1)": "N/A"})
            feature_rows.append({
                "Linguistic Feature": feat_name,
                "Your Text Value": f"{user_val:.4f}",
                "Human Dataset Avg": bench["Human (0)"],
                "AI Dataset Avg": bench["AI (1)"],
            })

        feat_df = pd.DataFrame(feature_rows)
        st.dataframe(feat_df, use_container_width=True, hide_index=True)

    # Mandatory Disclaimer
    st.markdown("---")
    st.warning(
        "⚠️ **Disclaimer:** AI detectors are not 100% accurate and can wrongly flag human writing "
        "(false positives). Results represent probabilistic pattern similarity, not absolute proof of authorship."
    )


if __name__ == "__main__":
    main()
